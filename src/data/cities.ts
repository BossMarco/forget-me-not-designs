export function getCity(slug: string): City | undefined {
  return CITIES.find((c) => c.slug === slug);
}

/** Cities that get their own indexable hub + occasion matrix (real cities/towns). */
export function isIndexableCity(city: City): boolean {
  return city.type === "city" || city.type === "town";
}

export const INDEXABLE_CITIES = CITIES.filter(isIndexableCity);
export const TIER1_CITIES = CITIES.filter((c) => c.tier === 1);
export const TIER2_CITIES = CITIES.filter((c) => c.tier === 2);

/** Group indexable cities by county for hub/index display. */
export function citiesByCounty(): Record<County, City[]> {
  const out: Record<County, City[]> = {
    Hidalgo: [],
    Cameron: [],
    Starr: [],
    Willacy: [],
  };
  for (const c of INDEXABLE_CITIES) out[c.county].push(c);
  return out;
}
